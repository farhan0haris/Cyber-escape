/**
 * Validate a scenario for single authenticity and decoy integrity
 * @param {Object} scenario
 * @returns {{ valid: boolean, errors: string[] }}
 */
export function validateScenario(scenario) {
  const errors = [];
  if (!scenario || !Array.isArray(scenario.chips)) {
    return { valid: false, errors: ['Invalid scenario structure: chips array missing'] };
  }

  if (scenario.chips.length !== 12) {
    errors.push(`Expected exactly 12 memory chips, got ${scenario.chips.length}`);
  }

  const authenticChips = scenario.chips.filter(c => c.isAuthentic === true);
  if (authenticChips.length !== 1) {
    errors.push(`Expected exactly 1 authentic chip, found ${authenticChips.length}`);
  }

  const idSet = new Set();
  const addressSet = new Set();

  scenario.chips.forEach((chip, index) => {
    if (!chip.id) errors.push(`Chip at index ${index} missing id`);
    if (idSet.has(chip.id)) errors.push(`Duplicate chip ID: ${chip.id}`);
    idSet.add(chip.id);

    if (!chip.address) errors.push(`Chip at index ${index} missing address`);
    if (addressSet.has(chip.address)) errors.push(`Duplicate address: ${chip.address}`);
    addressSet.add(chip.address);

    if (!chip.algorithm) errors.push(`Chip ${chip.id} missing algorithm`);
    if (!chip.fingerprint) errors.push(`Chip ${chip.id} missing fingerprint`);
    if (!chip.checksum) errors.push(`Chip ${chip.id} missing checksum`);
    if (!chip.origin) errors.push(`Chip ${chip.id} missing origin`);
    if (typeof chip.integrity !== 'number') errors.push(`Chip ${chip.id} missing numeric integrity`);

    // Ensure decoys have a defined failure reason
    if (!chip.isAuthentic && !chip.defectReason) {
      errors.push(`Decoy chip ${chip.id} missing defectReason`);
    }
  });

  return { valid: errors.length === 0, errors };
}

/**
 * In-memory recent scenario history for Level 3
 */
const recentLevel3Scenarios = [];

export function recordLevel3Scenario(scenarioId) {
  if (!scenarioId) return;
  recentLevel3Scenarios.unshift(scenarioId);
  if (recentLevel3Scenarios.length > 3) {
    recentLevel3Scenarios.pop();
  }
}

export function isRecentLevel3Scenario(scenarioId) {
  return recentLevel3Scenarios.includes(scenarioId);
}

export function clearLevel3ScenarioHistory() {
  recentLevel3Scenarios.length = 0;
}

export function getRecentLevel3Scenarios() {
  return [...recentLevel3Scenarios];
}
